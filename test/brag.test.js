const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname,'../server.js'),'utf8');
const start = source.indexOf('function bragScore(');
const end = source.indexOf('function solvePlayerHand(',start);
assert.ok(start >= 0 && end > start);
const context = { RANKS: ['2','3','4','5','6','7','8','9','T','J','Q','K','A'] };
vm.createContext(context);
vm.runInContext(source.slice(start,end),context);
const hand = (ranks,suits='♠♥♦') => [...ranks].map((rank,i)=>({rank,suit:suits[i]}));
const score = (ranks,suits) => Array.from(context.bragScore(hand(ranks,suits)));
const cmp = (a,b) => context.compareScores(a,b);
test('prial outranks running flush',()=>assert.ok(cmp(score('333'),score('AKQ','♠♠♠'))>0));
test('three threes highest prial',()=>assert.ok(cmp(score('333'),score('AAA'))>0));
test('running flush outranks run',()=>assert.ok(cmp(score('789','♠♠♠'),score('AKQ'))>0));
test('run outranks flush',()=>assert.ok(cmp(score('789'),score('AKJ','♠♠♠'))>0));
test('flush outranks pair',()=>assert.ok(cmp(score('AKJ','♠♠♠'),score('KK2'))>0));
test('pair outranks high card',()=>assert.ok(cmp(score('KK2'),score('AKJ'))>0));
test('A23 run outranks AKQ run',()=>assert.ok(cmp(score('A23'),score('AKQ'))>0));
test('pair kicker breaks tie',()=>assert.ok(cmp(score('KKQ'),score('KKJ'))>0));
test('equal hands tie',()=>assert.equal(cmp(score('AKJ'),score('AKJ')),0));
test('invalid hand size rejected',()=>assert.throws(()=>context.bragScore(hand('AK'))));
